"""Reference-guided local FLUX.2 Klein edits, preserving unselected source pixels.

Uses the installed ComfyUI core nodes and existing local HTTP queue. No package,
server or original-model changes; no cloud API. prepare is CPU-only. submit
queues exactly one edit; collect never submits/retries a generation.
"""
import argparse
from pathlib import Path
import uuid

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

from repaint_walk_parts import read, write, digest, request, upload


def prepare(config, name, out):
    config = read(config)
    job = config["edits"][name]
    if out.exists():
        raise FileExistsError("Choose a fresh edit directory")
    source = Path(job["source"]) if job.get("source") else Path(config["baseline"]) / "decoded" / job["frame"]
    alpha = Path(config["baseline"]) / "packaged/rgba-full" / job["frame"]
    out.mkdir(parents=True)
    image = Image.open(source).convert("RGB")
    if image.size != (1024, 1024):
        raise ValueError("Native-motion baseline must use the shared 1024 canvas")
    image.save(out / "source.png")
    crop = job.get("crop", [0, 0, 1024, 1024])
    if not (0 <= crop[0] < crop[2] <= 1024 and 0 <= crop[1] < crop[3] <= 1024):
        raise ValueError("Crop must remain inside the shared source canvas")
    if any(v % 16 for v in crop):
        raise ValueError("Edit crop must align with the FLUX latent grid")
    conditioning = image.copy()
    # Optional removal guide affects model input only. The final RGB/alpha is
    # generated by the neural editor; no erased polygon is used as output art.
    if job.get("guide_erase"):
        guide = Image.new("L", image.size)
        for polygon in job["guide_erase"]:
            ImageDraw.Draw(guide).polygon([tuple(p) for p in polygon], fill=255)
        guide = guide.filter(ImageFilter.GaussianBlur(2))
        sample = np.asarray(image.crop(job["guide_background_sample"])).reshape(-1, 3)
        color = tuple(int(v) for v in np.median(sample, axis=0))
        conditioning = Image.composite(Image.new("RGB", image.size, color), image, guide)
        guide.save(out / "conditioning-removal-guide.png")
    conditioning.crop(crop).save(out / "input.png")
    Image.open(alpha).convert("RGBA").save(out / "source-rgba.png")
    mask = Image.new("L", image.size)
    draw = ImageDraw.Draw(mask)
    for polygon in job["selections"]:
        draw.polygon([tuple(p) for p in polygon], fill=255)
    mask = mask.filter(ImageFilter.MaxFilter(13)).filter(ImageFilter.GaussianBlur(4))
    mask.save(out / "selection.png")
    references = []
    for index, ref in enumerate(job.get("references", []), 2):
        path = Path(ref)
        frame = Image.open(path).convert("RGB")
        if frame.size != image.size:
            raise ValueError("References use the same source canvas before downsampling")
        crops = job.get("reference_crops", [])
        if crops:
            frame = frame.crop(crops[index - 2])
        # References are conditioning, not alternate game-output resolutions.
        frame.resize((512, 512), Image.Resampling.LANCZOS).save(out / f"reference-{index}.png")
        references.append({"path": str(path), "sha256": digest(path),
                           "prepared": f"reference-{index}.png"})
    Image.composite(Image.blend(image, Image.new("RGB", image.size, (35, 210, 230)), .4),
                    image, mask).save(out / "selection-review.png")
    write(out / "job.json", {"schema": "simon-direct-reference-edit-v1", "status": "prepared",
          "job": job, "references": references, "source_sha256": digest(source),
          "selection_sha256": digest(out / "selection.png"), "local_only": True,
          "conditioning_sha256": digest(out / "input.png"),
          "game_installed": False, "artistic_approval": False,
          "model_guide": "https://docs.comfy.org/tutorials/flux/flux-2-klein"})


def graph_for(prompt, images, prefix, size, cpu_model=False):
    graph = {}
    def add(key, kind, **inputs):
        graph[str(key)] = {"class_type": kind, "inputs": inputs}
    add(1, "UNETLoader", unet_name="simon-klein/flux-2-klein-4b.safetensors", weight_dtype="default")
    add(2, "CLIPLoader", clip_name="simon-klein/qwen_3_4b.safetensors", type="flux2")
    add(3, "VAELoader", vae_name="simon-klein/flux2-vae.safetensors")
    model, clip = ["1", 0], ["2", 0]
    if cpu_model:
        add(21, "SelectModelDevice", model=model, device="cpu")
        add(22, "ModelComputeDtype", model=["21", 0], dtype="bf16")
        add(23, "SelectCLIPDevice", clip=clip, device="cpu")
        model, clip = ["22", 0], ["23", 0]
    add(4, "CLIPTextEncode", clip=clip, text=prompt)
    positive = ["4", 0]
    for index, image in enumerate(images):
        node = 30 + 3 * index
        add(node, "LoadImage", image=image)
        add(node + 1, "VAEEncode", pixels=[str(node), 0], vae=["3", 0])
        add(node + 2, "ReferenceLatent", conditioning=positive, latent=[str(node + 1), 0])
        positive = [str(node + 2), 0]
    # Distilled model's official four-step, CFG=1 reference-edit graph.
    add(5, "BasicGuider", model=model, conditioning=positive)
    add(6, "RandomNoise", noise_seed=20261022)
    add(7, "KSamplerSelect", sampler_name="euler")
    add(8, "Flux2Scheduler", steps=4, width=size[0], height=size[1])
    add(9, "EmptyFlux2LatentImage", width=size[0], height=size[1], batch_size=1)
    add(10, "SamplerCustomAdvanced", noise=["6", 0], guider=["5", 0], sampler=["7", 0],
        sigmas=["8", 0], latent_image=["9", 0])
    add(11, "VAEDecodeTiled", samples=["10", 0], vae=["3", 0], tile_size=512,
        overlap=64, temporal_size=64, temporal_overlap=8)
    add(20, "SaveImage", images=["11", 0], filename_prefix=prefix)
    return graph


def normalize_graph(graph):
    info = request("/object_info")
    for node in graph.values():
        kind = node["class_type"]
        if kind not in info:
            raise RuntimeError("Missing installed node: " + kind)
        for key, value in node["inputs"].items():
            spec = info[kind]["input"]["required"].get(key)
            if spec and isinstance(spec[0], list) and isinstance(value, str) and kind != "LoadImage":
                choices = [s for s in spec[0] if s.replace("\\", "/") == value.replace("\\", "/")]
                if not choices:
                    raise ValueError(f"Model or option unavailable: {kind}.{key}={value}")
                node["inputs"][key] = choices[0]
    return graph


def batch_submit(directories, report_path, batch_out):
    """One serial queue item, shared model instances, one requested edit per part."""
    if not 1 <= len(directories) <= 8 or batch_out.exists():
        raise ValueError("Use 1-8 prepared edits and a fresh batch report")
    models = read(report_path)
    if models["status"] != "complete":
        raise RuntimeError("Model download not verified")
    queue = request("/queue")
    if queue.get("queue_running") or queue.get("queue_pending"):
        raise RuntimeError("Shared queue busy; leave its current job running")
    prepared = [read(folder / "job.json") for folder in directories]
    if any(meta["status"] != "prepared" for meta in prepared):
        raise RuntimeError("Only fresh prepared edits may enter a batch")
    shared = {"1", "2", "3", "21", "22", "23"}
    merged, outputs = {}, []
    prefix = "simon_direct_batch/" + uuid.uuid4().hex
    for index, (folder, meta) in enumerate(zip(directories, prepared)):
        subfolder = prefix + "/" + folder.name
        images = [upload(folder / "input.png", subfolder)]
        images += [upload(folder / ref["prepared"], subfolder) for ref in meta["references"]]
        graph = graph_for(meta["job"]["prompt"], images, subfolder + "/edited",
                          Image.open(folder / "input.png").size, True)
        def key(old):
            return old if old in shared else str(int(old) + 100 * index)
        for old, node in graph.items():
            if index and old in shared:
                continue
            inputs = {name: [key(value[0]), value[1]] if isinstance(value, list) else value
                      for name, value in node["inputs"].items()}
            merged[key(old)] = {"class_type": node["class_type"], "inputs": inputs}
        outputs.append({"folder": str(folder.resolve()), "output_node": key("20"),
                        "output_prefix": subfolder + "/edited"})
    normalize_graph(merged)
    client_id = uuid.uuid4().hex
    write(batch_out, {"status": "submitting", "client_id": client_id, "outputs": outputs})
    for folder, meta, output in zip(directories, prepared, outputs):
        write(folder / "workflow_api.json", merged)
        meta.update(status="submitting", client_id=client_id, model_files=models["files"],
                    backend="cpu_bf16_on_shared_queue", server_port=8188,
                    output_node=output["output_node"], output_prefix=output["output_prefix"])
        write(folder / "job.json", meta)
    response = request("/prompt", {"prompt": merged, "client_id": client_id})
    if not response.get("prompt_id") or response.get("node_errors"):
        write(batch_out, {"status": "rejected", "response": response, "outputs": outputs})
        raise RuntimeError(str(response))
    for folder, meta in zip(directories, prepared):
        meta.update(status="queued", prompt_id=response["prompt_id"])
        write(folder / "job.json", meta)
    write(batch_out, {"status": "queued", "prompt_id": response["prompt_id"], "outputs": outputs})
    print(response["prompt_id"], flush=True)


def submit(out, download_report, cpu=False, cpu_model=False):
    meta = read(out / "job.json")
    if meta["status"] != "prepared":
        raise RuntimeError("Already submitted: collect this edit instead of generating it twice")
    models = read(download_report)
    if models["status"] != "complete":
        raise RuntimeError("Pinned model downloads must finish first")
    for file in models["files"]:
        if file["status"] not in ("verified", "verified_existing") or Path(file["path"]).stat().st_size != file["size"]:
            raise RuntimeError("Incomplete verified model: " + file["path"])
    queue = request("/queue")
    if queue.get("queue_running") or queue.get("queue_pending"):
        raise RuntimeError("Queue busy; leave the existing landscape/sprite job running")
    stats = request("/system_stats")
    if cpu:
        if any(str(d.get("type", "")).lower() != "cpu" for d in stats.get("devices", [])):
            raise RuntimeError("CPU fallback must use the separate CPU-only server")
        # The GPU server remains usable, but another landscape job could exhaust
        # the shared RAM. Never start CPU inference while that queue is occupied.
        from urllib.request import urlopen
        import json
        with urlopen("http://127.0.0.1:8188/queue", timeout=10) as response:
            other = json.load(response)
        if other.get("queue_running") or other.get("queue_pending"):
            raise RuntimeError("Shared RAM is in use by the landscape GPU job")
    elif not any(word in str(stats.get("devices", [])).lower() for word in ("amd", "radeon", "gfx1150")):
        raise RuntimeError("Expected the existing Radeon server")
    folder = "simon_direct_edit/" + uuid.uuid4().hex
    names = [upload(out / "input.png", folder)]
    names += [upload(out / ref["prepared"], folder) for ref in meta["references"]]
    graph = graph_for(meta["job"]["prompt"], names, folder + "/edited", Image.open(out / "input.png").size, cpu_model)
    normalize_graph(graph)
    write(out / "workflow_api.json", graph)
    meta.update(status="submitting", client_id=uuid.uuid4().hex, model_files=models["files"], gpu_before=stats,
                backend="cpu_bf16_on_shared_queue" if cpu_model else ("cpu" if cpu else "radeon"),
                server_port=8189 if cpu else 8188)
    write(out / "job.json", meta)
    result = request("/prompt", {"prompt": graph, "client_id": meta["client_id"]})
    if not result.get("prompt_id") or result.get("node_errors"):
        meta.update(status="rejected", submission=result)
        write(out / "job.json", meta)
        raise RuntimeError(str(result))
    meta.update(status="queued", prompt_id=result["prompt_id"])
    write(out / "job.json", meta)
    print(meta["prompt_id"], flush=True)


def collect(out):
    from urllib.parse import urlencode
    meta = read(out / "job.json")
    history = request("/history/" + meta["prompt_id"]).get(meta["prompt_id"])
    if not history:
        print("Waiting for " + meta["prompt_id"])
        return
    write(out / "history.json", history)
    if history["status"].get("status_str") == "error":
        meta.update(status="failed")
        write(out / "job.json", meta)
        raise RuntimeError("Direct edit failed; inspect history.json")
    if not history["status"].get("completed"):
        print("Still executing")
        return
    if history["prompt"][2] != read(out / "workflow_api.json"):
        raise ValueError("Executed graph differs from the saved edit graph")
    image = history["outputs"][meta.get("output_node", "20")]["images"][0]
    (out / "generated.png").write_bytes(request("/view?" + urlencode(image), raw=True))
    source = Image.open(out / "source.png").convert("RGB")
    generated = Image.open(out / "generated.png").convert("RGB")
    crop = meta["job"].get("crop", [0, 0, 1024, 1024])
    if generated.size != (crop[2] - crop[0], crop[3] - crop[1]):
        raise ValueError("The edit crop must retain its exact size without resizing")
    full_generated = source.copy()
    full_generated.paste(generated, crop)
    selection = Image.open(out / "selection.png").convert("L")
    result = Image.composite(full_generated, source, selection)
    result.save(out / "edited-full.png")
    unchanged = np.array_equal(np.array(result)[np.array(selection) == 0],
                               np.array(source)[np.array(selection) == 0])
    if not unchanged:
        raise ValueError("Pixels outside the selection changed")
    compare = Image.new("RGB", (1024, 512))
    compare.paste(source.resize((512, 512), Image.Resampling.LANCZOS), (0, 0))
    compare.paste(result.resize((512, 512), Image.Resampling.LANCZOS), (512, 0))
    compare.save(out / "comparison.png")
    meta.update(status="rendered_needs_visual_review", unchanged_outside_selection=True,
                generated_sha256=digest(out / "generated.png"), history_sha256=digest(out / "history.json"))
    write(out / "job.json", meta)
    print(meta["status"])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest="command", required=True)
    prep = sub.add_parser("prepare")
    prep.add_argument("--config", type=Path, required=True)
    prep.add_argument("--edit", required=True)
    prep.add_argument("--out", type=Path, required=True)
    run = sub.add_parser("submit")
    run.add_argument("--out", type=Path, required=True)
    run.add_argument("--download-report", type=Path, required=True)
    run.add_argument("--cpu", action="store_true", help="Use isolated CPU-only server on 8189 after a GPU failure")
    run.add_argument("--cpu-model", action="store_true", help="Use installed per-model CPU/BF16 nodes on the shared 8188 queue")
    get = sub.add_parser("collect")
    get.add_argument("--out", type=Path, required=True)
    batch = sub.add_parser("batch")
    batch.add_argument("--parts", type=Path, nargs="+", required=True)
    batch.add_argument("--download-report", type=Path, required=True)
    batch.add_argument("--out", type=Path, required=True)
    args = p.parse_args()
    if (getattr(args, "cpu", False) or
        args.command == "collect" and read(args.out / "job.json").get("server_port") == 8189):
        import repaint_walk_parts
        repaint_walk_parts.SERVER = "http://127.0.0.1:8189"
    if args.command == "prepare":
        prepare(args.config, args.edit, args.out)
    elif args.command == "submit":
        if args.cpu and args.cpu_model:
            raise ValueError("Choose one CPU backend")
        submit(args.out, args.download_report, args.cpu, args.cpu_model)
    elif args.command == "batch":
        batch_submit(args.parts, args.download_report, args.out)
    else:
        collect(args.out)


if __name__ == "__main__":
    main()
